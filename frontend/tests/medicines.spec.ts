import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';

test('catalogue import, allergy acknowledgement and saved medicine persist', async ({ page }, testInfo) => {
  const email = `medicine-${Date.now()}@example.com`;
  await page.goto('/');
  await page.getByRole('tab', { name: 'Create account' }).click();
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Medicine Demo');
  await page.getByRole('textbox', { name: 'Email address', exact: true }).fill(email);
  await page.getByLabel(/^Password/).fill('Browser-demo-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your care circles' })).toBeVisible();
  const backend = path.resolve('../backend');
  const python = process.env.E2E_PYTHON || path.join(backend, process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  execFileSync(python, ['-m', 'tests.browser_admin', email], { cwd: backend, env: process.env });
  await page.reload();
  await page.getByRole('button', { name: 'Create patient profile' }).click();
  await page.getByRole('textbox', { name: 'Patient name', exact: true }).fill('Medicine Demo');
  await page.getByLabel('Consent / authority statement').fill('I consent to this synthetic browser-test profile.');
  await page.getByRole('checkbox', { name: 'I confirm this consent statement' }).check();
  await page.getByRole('button', { name: 'Create profile', exact: true }).click();
  await page.getByLabel('CSV content').fill(readFileSync(path.join(backend, 'data/medicines-demo.csv'), 'utf8'));
  await page.getByRole('button', { name: 'Validate and import CSV' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Imported' })).toBeVisible();
  await page.getByLabel('Allergy generic names (one per line)').fill('Demo compound alpha');
  await page.getByRole('button', { name: 'Save reported allergies' }).click();
  await expect(page.getByText('Reported allergies saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Choose Demo Alpha', exact: true }).click();
  await page.getByLabel('Start date', { exact: true }).fill(new Date().toISOString().slice(0, 10));
  await page.getByRole('button', { name: 'Add to proposed list' }).click();
  await page.getByRole('button', { name: 'Check proposed medicines' }).click();
  await expect(page.getByText('allergy · critical', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Confirm medicine record' })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('heading', { name: 'Warning review' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('warning-mobile.png') });
  await page.getByRole('checkbox', { name: 'I have reviewed this allergy warning' }).check();
  await page.getByRole('button', { name: 'Confirm medicine record' }).click();
  await expect(page.getByText('Medicine record saved. Dose scheduling is not integrated yet.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText(/^Demo Alpha · 1(?:\.0+)? tablet$/)).toBeVisible();
});

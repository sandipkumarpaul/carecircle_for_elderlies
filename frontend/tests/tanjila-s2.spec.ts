import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';

test('printed OCR review, prescription revision and stop preserve history', async ({ page }, testInfo) => {
  const email = `ocr-${Date.now()}@example.com`;
  await page.goto('/');
  await page.getByRole('tab', { name: 'Create account' }).click();
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Medicine Demo');
  await page.getByRole('textbox', { name: 'Email address', exact: true }).fill(email);
  await page.getByLabel(/^Password/).fill('Browser-demo-password-123');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your care circles' })).toBeVisible();
  const backend = path.resolve('../backend');
  const python = process.env.E2E_PYTHON || path.join(backend, process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
  execFileSync(python, ['-m', 'tests.browser_admin', email], { cwd: backend, env: process.env });
  await page.reload();
  await page.getByRole('button', { name: 'Create patient profile' }).click();
  await page.getByRole('textbox', { name: 'Patient name', exact: true }).fill('Medicine Demo');
  await page.getByLabel('Consent / authority statement').fill('I consent to this synthetic browser-test profile.');
  await page.getByRole('checkbox', { name: 'I confirm this consent statement' }).check();
  await page.getByRole('button', { name: 'Create profile', exact: true }).click();
  await page.getByLabel('CSV content').fill(readFileSync(path.join(backend, 'data/medicines-demo.csv'), 'utf8'));
  await page.getByRole('button', { name: 'Validate and import CSV' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Imported' })).toBeVisible();
  await page.getByTestId('prescription-image').setInputFiles(path.join(backend, 'data/prescription-demo.png'));
  await page.getByRole('button', { name: 'Extract prescription text', exact: true }).click();
  await expect(page.getByLabel('Reviewed prescription text', { exact: true })).toHaveValue(/Demo Alpha/);
  await page.getByLabel('Reviewed prescription text', { exact: true }).fill('Demo Alpha 10mg tablet. Printed synthetic prescription reviewed.');
  await page.getByRole('button', { name: 'Save reviewed text', exact: true }).click();
  await expect(page.getByText('Reviewed text saved. Verify each catalogue suggestion before choosing it.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Use suggestion: Demo Alpha', exact: true }).click();
  const tomorrow = new Date(Date.now() + 86400000).toISOString().slice(0, 10);
  await page.getByLabel('Start date', { exact: true }).fill(tomorrow);
  await page.getByLabel('Local times (HH:MM, comma separated)', { exact: true }).fill('08:00, 20:00');
  await page.getByRole('button', { name: 'Add to proposed list', exact: true }).click();
  await page.getByRole('button', { name: 'Check proposed medicines', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm medicine record', exact: true }).click();
  await expect(page.getByText('Medicine record saved and dose schedule generated.', { exact: true })).toBeVisible();
  await expect(page.getByTestId('scheduled-dose').first()).toBeVisible();
  await page.getByRole('button', { name: 'Revise this prescription', exact: true }).click();
  await page.getByLabel('Reason for revision', { exact: true }).fill('Recorded updated clinician instruction for demonstration');
  await page.getByRole('button', { name: 'Edit item 1', exact: true }).click();
  await page.getByLabel('Quantity per dose (tablet)', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Add to proposed list', exact: true }).click();
  await page.getByRole('button', { name: 'Check proposed medicines', exact: true }).click();
  await expect(page.getByText('No matches in the limited reference rules.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm medicine record', exact: true }).click();
  await expect(page.getByTestId('prescription-version')).toHaveCount(2);
  await expect(page.getByText('Version 2 · Current', { exact: true })).toBeVisible();
  await expect(page.getByText('Version 1 · Previous', { exact: true })).toBeVisible();
  await expect(page.getByTestId('scheduled-dose').first()).toContainText(/2(?:\.0+)? tablet/);
  await page.getByRole('button', { name: 'Refresh alerts', exact: true }).click();
  await expect(page.getByTestId('alert-entry').getByRole('heading', { name: 'Prescription changed' })).toBeVisible();
  await page.getByRole('button', { name: 'Stop this prescription', exact: true }).click();
  await page.getByLabel('Reason for stopping', { exact: true }).fill('Recorded clinician stop instruction');
  await page.getByRole('button', { name: 'Confirm stop', exact: true }).click();
  await expect(page.getByText('Version 3 · Stopped', { exact: true })).toBeVisible();
  await expect(page.getByTestId('scheduled-dose')).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId('prescription-version')).toHaveCount(3);
  await expect(page.getByText('Version 3 · Stopped', { exact: true })).toBeVisible();
  await expect(page.getByTestId('alert-entry')).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('heading', { name: 'Prescription version history', exact: true }).locator('..').screenshot({ path: testInfo.outputPath('history-mobile.png') });
});
